#!/usr/bin/env bash
set -euo pipefail

# Verify all GroundKV Dafny proofs (Phase 1 + Phase 2), audit for zero
# `assume` / `{:verify false}` cheats, and compile verified Go packages
# into engine/verified/internal/dafnygen/.

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DAFNY_BIN="${DAFNY:-$HOME/.local/dafny/dafny}"
if ! command -v "$DAFNY_BIN" >/dev/null 2>&1; then
  if command -v dafny >/dev/null 2>&1; then
    DAFNY_BIN="dafny"
  else
    echo "ERROR: dafny binary not found (checked \$DAFNY, ~/.local/dafny/dafny, PATH)" >&2
    exit 1
  fi
fi

# Ensure goimports is on PATH for Dafny's Go backend
export PATH="$(go env GOPATH)/bin:$PATH"
if ! command -v goimports >/dev/null 2>&1; then
  echo "ERROR: goimports not found on PATH (required by dafny translate go)" >&2
  exit 1
fi

SKIP_VERIFY="${SKIP_VERIFY:-0}"

cd "$ROOT_DIR"

echo "==> Checking Dafny sources for forbidden verification bypasses..."
if grep -rnE '\bassume\b|\{:verify\s+false\}|\{:axiom\}' formal/dafny/*.dfy; then
  echo "ERROR: Forbidden verification bypass (assume / {:verify false} / {:axiom}) found!" >&2
  exit 1
fi
echo "    OK: zero assume / {:verify false} / {:axiom} in formal/dafny/*.dfy"

if [ "$SKIP_VERIFY" != "1" ]; then
  echo "==> Verifying all Phase 1 & Phase 2 Dafny modules..."
  "$DAFNY_BIN" verify --verify-included-files formal/dafny/GroundKV.dfy
fi

TMP_OUT="$(mktemp -d /tmp/groundkv-dafny-go-XXXXXX)"
trap 'rm -rf "$TMP_OUT"' EXIT

echo "==> Translating verified Dafny modules to Go..."
"$DAFNY_BIN" translate go \
  --no-verify \
  --include-runtime \
  --go-module-name github.com/flaneur2020/groundkv/engine/verified/internal/dafnygen \
  --output "$TMP_OUT/dafnygen" \
  formal/dafny/GroundKV.dfy

GEN_SRC="$TMP_OUT/dafnygen-go"
DEST="$ROOT_DIR/engine/verified/internal/dafnygen"
rm -rf "$DEST"
mkdir -p "$DEST"

# Copy generated Go packages (runtime + System_ + all GroundKV* modules)
for pkg in dafny System_ GroundKVTypes GroundKVCodec GroundKVNode GroundKVFreelist GroundKVBTree GroundKVEngine; do
  if [ -d "$GEN_SRC/$pkg" ]; then
    cp -r "$GEN_SRC/$pkg" "$DEST/$pkg"
  fi
done

# Dafny 4.11 omits the --go-module-name prefix in bundled System_/System_.go.
if [ -f "$DEST/System_/System_.go" ]; then
  sed -i 's|_dafny "dafny"|_dafny "github.com/flaneur2020/groundkv/engine/verified/internal/dafnygen/dafny"|g' "$DEST/System_/System_.go"
fi

# Mark all generated Go files with standard Go code-generation header.
while IFS= read -r -d '' gofile; do
  if ! head -n 1 "$gofile" | grep -q '^// Code generated by Dafny'; then
    tmpf="${gofile}.tmp"
    {
      echo "// Code generated by Dafny from formal/dafny/*.dfy. DO NOT EDIT."
      echo ""
      cat "$gofile"
    } > "$tmpf"
    mv "$tmpf" "$gofile"
  fi
done < <(find "$DEST" -name '*.go' -print0)

echo "==> Generated Go packages under engine/verified/internal/dafnygen/:"
find "$DEST" -name '*.go' | sort
